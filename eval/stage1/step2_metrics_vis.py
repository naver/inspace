def find_pred_samples(pred_dir: str) -> List[dict]:
    """Find all generated NPZ files. Returns list of dicts with uuid, room_name, view_idx, pred_path."""
    samples = []
    if not os.path.isdir(pred_dir):
        return samples
    for uuid_dir in sorted(os.listdir(pred_dir)):
        uuid_path = os.path.join(pred_dir, uuid_dir)
        if not os.path.isdir(uuid_path) or uuid_dir.startswith('.'):
            continue
        for room_name in sorted(os.listdir(uuid_path)):
            room_path = os.path.join(uuid_path, room_name)
            if not os.path.isdir(room_path):
                continue
            for npz_file in sorted(glob(os.path.join(room_path, '*.npz'))):
                view_idx = int(os.path.splitext(os.path.basename(npz_file))[0])
                samples.append({
                    'uuid': uuid_dir,
                    'room_name': room_name,
                    'view_idx': view_idx,
                    'pred_path': npz_file,
                })
    return samples


def build_lookup(samples: List[dict]) -> Dict[str, str]:
    """Build key→pred_path lookup from sample list."""
    lookup = {}
    for s in samples:
        key = f"{s['uuid']}/{s['room_name']}/{s['view_idx']:04d}"
        lookup[key] = s['pred_path']
    return lookup


def load_pred_voxel(pred_path: str) -> Optional[torch.Tensor]:
    """Load predicted voxel from NPZ. Returns [1,64,64,64] bool tensor."""
    if not os.path.exists(pred_path):
        return None
    data = np.load(pred_path)
    return torch.tensor(data['voxel'])  # [1, 64, 64, 64]


def load_gt_voxel(
    data_dir: str, uuid: str, room_name: str,
    resolution: int = 64,
    gt_voxel_folder: str = 'voxels_64',
) -> Optional[torch.Tensor]:
    """Load GT voxel from pre-computed PLY file. Returns [1, 64, 64, 64] bool tensor."""
    path = os.path.join(data_dir, uuid, room_name, gt_voxel_folder, 'full_room_wo_ceiling.ply')
    if not os.path.exists(path):
        return None
    pcd = o3d.io.read_point_cloud(path)
    pts = np.asarray(pcd.points)
    if pts.shape[0] == 0:
        return None
    # PLY coords are voxel centers in [-0.5, 0.5] → integer indices [0, resolution-1]
    indices = np.round((pts + 0.5) * resolution - 0.5).astype(np.int64)
    indices = np.clip(indices, 0, resolution - 1)
    grid = torch.zeros(1, resolution, resolution, resolution, dtype=torch.bool)
    grid[0, indices[:, 0], indices[:, 1], indices[:, 2]] = True
    return grid


def load_cubemap_images(data_dir: str, uuid: str, room_name: str, view_idx: int, size: int = 512) -> Optional[torch.Tensor]:
    """Load 6 cubemap faces. Returns [6, 3, size, size]."""
    faces = ['front', 'right', 'back', 'left', 'top', 'bottom']
    cubic_path = os.path.join(data_dir, uuid, room_name, 'cubic_fov_120', f'{view_idx:04d}')
    if not os.path.isdir(cubic_path):
        return None
    imgs = []
    for face in faces:
        p = os.path.join(cubic_path, f'{face}.png')
        if not os.path.exists(p):
            return None
        img = Image.open(p).convert('RGB').resize((size, size), Image.Resampling.LANCZOS)
        imgs.append(torch.tensor(np.array(img)).permute(2, 0, 1).float() / 255.0)
    return torch.stack(imgs)


def load_camera_center(data_dir: str, uuid: str, room_name: str, view_idx: int) -> Optional[np.ndarray]:
    """Load and normalize camera center. Returns [3] numpy array."""
    room = os.path.join(data_dir, uuid, room_name)
    cp_path = os.path.join(room, 'camera_poses.json')
    ni_path = os.path.join(room, 'mesh_dumps', 'normalization_info.json')
    if not os.path.exists(cp_path) or not os.path.exists(ni_path):
        return None
    with open(cp_path) as f:
        cp = json.load(f)
    with open(ni_path) as f:
        ni = json.load(f)
    loc = None
    for v in cp.get('views', []):
        if v.get('view_idx') == view_idx:
            loc = v.get('location')
            break
    if loc is None:
        return None
    center = np.array(ni['center'], dtype=np.float32)
    scale = float(ni['scale'])
    return (np.array(loc, dtype=np.float32) - center) * scale


