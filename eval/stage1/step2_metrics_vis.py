def _depth_to_normal(depth: torch.Tensor, alpha: torch.Tensor) -> torch.Tensor:
    """Compute screen-space normals from depth map via finite differences.

    Args:
        depth: [H, W] depth map
        alpha: [H, W] alpha/coverage map

    Returns: [3, H, W] normal map in [0, 1] range (0.5 = flat)
    """
    mask = alpha > 0.5
    d = depth.clone()
    d[~mask] = 0

    # Finite differences
    dz_dx = torch.zeros_like(d)
    dz_dy = torch.zeros_like(d)
    dz_dx[:, 1:-1] = (d[:, 2:] - d[:, :-2]) / 2.0
    dz_dy[1:-1, :] = (d[2:, :] - d[:-2, :]) / 2.0

    # Normal = normalize(-dz/dx, -dz/dy, 1)
    normal = torch.stack([-dz_dx, -dz_dy, torch.ones_like(d)], dim=0)  # [3, H, W]
    norm = normal.norm(dim=0, keepdim=True).clamp(min=1e-6)
    normal = normal / norm

    # Map [-1, 1] → [0, 1] and apply mask
    normal = normal * 0.5 + 0.5
    bg = torch.full_like(normal, 0.5)  # neutral gray background
    normal = torch.where(mask.unsqueeze(0), normal, bg)
    return normal


def _height_colormap(coords: torch.Tensor, resolution: int = 64) -> torch.Tensor:
    """Map voxel height (Z axis) to turbo colormap.

    Normalizes to actual min/max Z of occupied voxels so the full
    colormap range is used regardless of where the scene sits in the grid.

    Args:
        coords: [N, 3] integer voxel coordinates
        resolution: voxel grid resolution

    Returns: [N, 3] RGB colors in [0, 1]
    """
    import matplotlib.cm as cm
    z = coords[:, 2].float()
    z_min, z_max = z.min(), z.max()
    if z_max - z_min < 1e-6:
        height = torch.zeros_like(z)
    else:
        height = (z - z_min) / (z_max - z_min)  # normalize to [0, 1] within actual range
    height_np = height.cpu().numpy()
    cmap = cm.get_cmap('turbo')
    colors_np = cmap(height_np)[:, :3]  # [N, 3] RGB
    return torch.from_numpy(colors_np.astype(np.float32))


def _ccm_colormap(coords: torch.Tensor) -> torch.Tensor:
    """Map voxel (x, y, z) to (R, G, B), normalized to actual occupied range per axis."""
    c = coords.float()
    c_min = c.min(dim=0).values  # [3]
    c_max = c.max(dim=0).values  # [3]
    span = (c_max - c_min).clamp(min=1.0)
    return (c - c_min) / span  # [N, 3] in [0, 1]


def _make_voxel_rep(coords, color, resolution):
    """Create a Voxel representation for rendering."""
    return Voxel(
        origin=[-0.5, -0.5, -0.5],
        voxel_size=1.0 / resolution,
        coords=coords.cuda(),
        attrs=color.cuda(),
        layout={'color': slice(0, 3)},
    )


def _make_renderer(tile, near=0.8, far=1.6, ssaa=4):
    """Create a VoxelRenderer with standard settings."""
    renderer = VoxelRenderer()
    renderer.rendering_options.resolution = tile
    renderer.rendering_options.near = near
    renderer.rendering_options.far = far
    renderer.rendering_options.ssaa = ssaa
    return renderer


def _render_single_view(renderer, rep, color, ext, intr, color_mode='ccm'):
    """Render a single view, returning [3, H, W] image.

    color_mode: 'ccm' (coordinate color), 'normal' (screen-space normal), 'height' (already baked in color)
    """
    res = renderer.render(rep, ext, intr, colors_overwrite=color.cuda())
    if color_mode == 'normal':
        return _depth_to_normal(res['depth'], res['alpha'])
    return res['color']


@torch.no_grad()
def render_exterior(voxel_grid: torch.Tensor, resolution: int = 64, tile: int = 256,
                    color_mode: str = 'ccm') -> torch.Tensor:
    """
    Render 4 exterior views arranged in 2x2 grid.

    Args:
        color_mode: 'ccm' (position→RGB), 'normal' (screen-space normals), 'height' (turbo colormap by Z)

    Returns: [3, 2*tile, 2*tile] tensor
    """
    grid = voxel_grid.squeeze()
    coords = torch.nonzero(grid > 0, as_tuple=False)

    if coords.shape[0] == 0:
        return torch.zeros(3, 2 * tile, 2 * tile)

    if color_mode == 'height':
        color = _height_colormap(coords, resolution)
    else:
        color = _ccm_colormap(coords)
    rep = _make_voxel_rep(coords, color, resolution)
    renderer = _make_renderer(tile)

    yaw_offset = -16 / 180 * np.pi
    yaws = [i * np.pi / 2 + yaw_offset for i in range(4)]
    pitch = [20 / 180 * np.pi] * 4
    exts, ints = yaw_pitch_r_fov_to_extrinsics_intrinsics(yaws, pitch, 2, 30)

    image = torch.zeros(3, 2 * tile, 2 * tile).cuda()
    for j, (ext, intr) in enumerate(zip(exts, ints)):
        face = _render_single_view(renderer, rep, color, ext, intr, color_mode)
        r, c = j // 2, j % 2
        image[:, r * tile:(r + 1) * tile, c * tile:(c + 1) * tile] = face

    return image.cpu()


@torch.no_grad()
def render_topdown(voxel_grid: torch.Tensor, resolution: int = 64, tile: int = 256,
                   color_mode: str = 'ccm') -> torch.Tensor:
    """Render single top-down view. Returns [3, tile, tile]."""
    grid = voxel_grid.squeeze()
    coords = torch.nonzero(grid > 0, as_tuple=False)

    if coords.shape[0] == 0:
        return torch.zeros(3, tile, tile)

    if color_mode == 'height':
        color = _height_colormap(coords, resolution)
    else:
        color = _ccm_colormap(coords)
    rep = _make_voxel_rep(coords, color, resolution)
    renderer = _make_renderer(tile)

    exts, ints = yaw_pitch_r_fov_to_extrinsics_intrinsics([0], [90 / 180 * np.pi], 2, 30)
    face = _render_single_view(renderer, rep, color, exts[0], ints[0], color_mode)
    return face.cpu()


@torch.no_grad()
def render_topdown_cam(
    voxel_grid: torch.Tensor,
    camera_center: np.ndarray,
    resolution: int = 64,
    tile: int = 256,
    color_mode: str = 'ccm',
) -> torch.Tensor:
    """Render top-down view with camera center overlay. Returns [3, tile, tile]."""
    face = render_topdown(voxel_grid, resolution, tile, color_mode=color_mode)

    # Project camera center onto top-down image
    exts, ints_mat = yaw_pitch_r_fov_to_extrinsics_intrinsics([0], [90 / 180 * np.pi], 2, 30)
    cam_3d = torch.tensor(camera_center, dtype=torch.float32).cuda()
    point_h = torch.cat([cam_3d, torch.ones(1, device='cuda')])
    point_cam = exts[0] @ point_h
    point_proj = ints_mat[0] @ point_cam[:3]

    if point_proj[2].abs() > 1e-6:
        px = (point_proj[0] / point_proj[2]).item() * tile
        py = (point_proj[1] / point_proj[2]).item() * tile

        if -20 < px < tile + 20 and -20 < py < tile + 20:
            img_np = (face.permute(1, 2, 0).numpy() * 255).clip(0, 255).astype(np.uint8)
            pil_img = Image.fromarray(img_np)
            draw = ImageDraw.Draw(pil_img)
            r = 6
            draw.ellipse([px - r, py - r, px + r, py + r], fill=(0, 255, 255), outline=(255, 255, 255), width=2)
            face = torch.tensor(np.array(pil_img)).permute(2, 0, 1).float() / 255.0

    return face


@torch.no_grad()
def render_interior(
    voxel_grid: torch.Tensor,
    camera_center: np.ndarray,
    resolution: int = 64,
    tile: int = 256,
    color_mode: str = 'ccm',
) -> torch.Tensor:
    """
    Render 6 interior cubemap faces from camera center.

    Returns: [6, 3, tile, tile]
    """
    grid = voxel_grid.squeeze()
    coords = torch.nonzero(grid > 0, as_tuple=False)

    if coords.shape[0] == 0:
        return torch.zeros(6, 3, tile, tile)

    world_scale = 10.0
    if color_mode == 'height':
        color = _height_colormap(coords, resolution)
    else:
        color = _ccm_colormap(coords)
    rep = Voxel(
        origin=[-0.5 * world_scale, -0.5 * world_scale, -0.5 * world_scale],
        voxel_size=world_scale / resolution,
        coords=coords.cuda(),
        attrs=color.cuda(),
        layout={'color': slice(0, 3)},
    )

    renderer = _make_renderer(tile, near=0.01 * world_scale, far=2.0 * world_scale)

    cam = torch.tensor(camera_center, dtype=torch.float32).cuda() * world_scale
    fov = torch.deg2rad(torch.tensor(120.0)).cuda()

    face_dirs = [
        [0, 1, 0], [1, 0, 0], [0, -1, 0], [-1, 0, 0], [0, 0, 1], [0, 0, -1],
    ]

    images = []
    for fi, fd in enumerate(face_dirs):
        look_at = cam + torch.tensor(fd, dtype=torch.float32).cuda()
        if fi == 4:
            up = torch.tensor([0.0, -1.0, 0.0], dtype=torch.float32).cuda()
        elif fi == 5:
            up = torch.tensor([0.0, 1.0, 0.0], dtype=torch.float32).cuda()
        else:
            up = torch.tensor([0.0, 0.0, 1.0], dtype=torch.float32).cuda()
        ext = utils3d.torch.extrinsics_look_at(cam, look_at, up)
        intr = utils3d.torch.intrinsics_from_fov_xy(fov, fov)
        face = _render_single_view(renderer, rep, color, ext, intr, color_mode)
        images.append(face.cpu())

    return torch.stack(images)


