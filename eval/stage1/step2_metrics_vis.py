def _label_strip(labels: list, cell_w: int, h: int = 28) -> Image.Image:
    """Create a white strip with centered text labels."""
    w = sum(cell_w) if isinstance(cell_w, list) else len(labels) * cell_w
    strip = Image.new('RGB', (w, h), (255, 255, 255))
    draw = ImageDraw.Draw(strip)
    font, _ = _get_font()
    x = 0
    for i, label in enumerate(labels):
        cw = cell_w[i] if isinstance(cell_w, list) else cell_w
        bbox = draw.textbbox((0, 0), label, font=font)
        tw = bbox[2] - bbox[0]
        draw.text((x + (cw - tw) // 2, 2), label, fill=(0, 0, 0), font=font)
        x += cw
    return strip


def _row_label(text: str, h: int, w: int = 120) -> Image.Image:
    """Create a vertical row label."""
    img = Image.new('RGB', (w, h), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    font, _ = _get_font()
    bbox = draw.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0]
    th = bbox[3] - bbox[1]
    draw.text(((w - tw) // 2, (h - th) // 2), text, fill=(0, 0, 0), font=font)
    return img


def _tensor_to_pil(t: torch.Tensor) -> Image.Image:
    """Convert [3,H,W] tensor to PIL Image."""
    arr = (t.permute(1, 2, 0).cpu().numpy() * 255).clip(0, 255).astype(np.uint8)
    return Image.fromarray(arr)


def save_batch_comparison(
    row_data: List[List[torch.Tensor]],
    row_labels: List[str],
    col_labels: List[str],
    output_path: str,
):
    """
    Save a comparison grid image.

    Args:
        row_data: List of rows, each row is a list of [3, H, W] tensors.
        row_labels: Label for each row (e.g., ['GT', 'Model1', ...]).
        col_labels: Label for each column (sample names).
        output_path: Path to save PNG.
    """
    n_rows = len(row_data)
    n_cols = len(row_data[0])

    # Get cell size from first image
    cell_h = row_data[0][0].shape[1]
    cell_w = row_data[0][0].shape[2]

    pad = 2
    label_w = 120
    label_h = 28

    total_w = label_w + n_cols * (cell_w + pad) - pad
    total_h = label_h + n_rows * (cell_h + pad) - pad

    canvas = Image.new('RGB', (total_w, total_h), (40, 40, 40))

    # Column labels
    strip = _label_strip(col_labels, cell_w + pad)
    canvas.paste(strip, (label_w, 0))

    # Rows
    for ri, (row, label) in enumerate(zip(row_data, row_labels)):
        y = label_h + ri * (cell_h + pad)
        # Row label
        rl = _row_label(label, cell_h)
        canvas.paste(rl, (0, y))
        # Images
        for ci, img_t in enumerate(row):
            x = label_w + ci * (cell_w + pad)
            canvas.paste(_tensor_to_pil(img_t), (x, y))

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    canvas.save(output_path)


def save_interior_comparison(
    cubemap: torch.Tensor,
    gt_interior: torch.Tensor,
    model_interiors: List[torch.Tensor],
    model_names: List[str],
    output_path: str,
):
    """
    Save per-sample interior comparison: Input / GT / Model1 / ... / ModelN x 6 faces.

    Args:
        cubemap: [6, 3, H, W] input cubemap images
        gt_interior: [6, 3, H, W] GT interior renders
        model_interiors: List of [6, 3, H, W] tensors per model
        model_names: List of display names per model
        output_path: Save path
    """
    face_names = ['front', 'right', 'back', 'left', 'top', 'bottom']
    tile = cubemap.shape[2]

    rows = [cubemap, gt_interior] + model_interiors
    labels = ['Input', 'GT'] + model_names

    n_rows = len(rows)
    pad = 2
    label_w = 120
    label_h = 28

    total_w = label_w + 6 * (tile + pad) - pad
    total_h = label_h + n_rows * (tile + pad) - pad

    canvas = Image.new('RGB', (total_w, total_h), (40, 40, 40))

    # Face name labels
    strip = _label_strip(face_names, tile + pad)
    canvas.paste(strip, (label_w, 0))

    for ri, (imgs, label) in enumerate(zip(rows, labels)):
        y = label_h + ri * (tile + pad)
        rl = _row_label(label, tile)
        canvas.paste(rl, (0, y))
        for fi in range(6):
            x = label_w + fi * (tile + pad)
            img = imgs[fi]
            if img.shape[1] != tile:
                img = F.interpolate(img.unsqueeze(0), size=(tile, tile), mode='bilinear', align_corners=False).squeeze(0)
            canvas.paste(_tensor_to_pil(img), (x, y))

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    canvas.save(output_path)


# ---------------------------------------------------------------------------
# Short name helper
# ---------------------------------------------------------------------------

def _make_short_name(name: str) -> str:
    """Create a short display name from directory name.

    Examples:
        erp_ss_flow_img_dit_L_16l8_bf16                          → wo_spatial
        erp_ss_flow_img_dit_L_16l8_bf16_spatial                   → spatial
        erp_ss_flow_img_dit_L_16l8_bf16_spatial_Da2_inversion_0.3 → spatial_Da2_inv_0.3
    """
    # Strip common prefix
    s = name.replace('erp_ss_flow_img_dit_L_16l8_', '')
    # Strip bf16 prefix
    if s.startswith('bf16_'):
        s = s[len('bf16_'):]
    elif s == 'bf16':
        s = 'wo_spatial'
    # Shorten Da2_inversion → Da2_inv
    s = s.replace('Da2_inversion', 'Da2_inv')
    return s


