def main():
    parser = argparse.ArgumentParser(description='Evaluate SS generation: N-model comparison')
    # parser.add_argument('--pred_dirs', type=str, nargs='+', required=True,
    #                     help='Prediction directories (from step1). First one is the reference for sample discovery.')
    parser.add_argument('--model_names', type=str, nargs='*', default=[],
                        help='Display names for models (default: derived from pred_dirs)')
    # parser.add_argument('--data_dir', type=str, required=True,
    #                     help='GT data directory (ERP_3D_FRONT)')
    parser.add_argument('--output_dir', type=str, default='',
                        help='Output directory (default: evals/results/ss_comparison)')
    parser.add_argument('--num_samples', type=int, default=0,
                        help='Max samples for metrics (0 = all)')
    parser.add_argument('--num_vis', type=int, default=100,
                        help='Number of samples to visualize')
    parser.add_argument('--batch_vis', type=int, default=6,
                        help='Number of samples per comparison PNG')
    parser.add_argument('--tile_size', type=int, default=256,
                        help='Tile size for individual renders')
    parser.add_argument('--interior_tile', type=int, default=256,
                        help='Tile size for interior cubemap renders')
    parser.add_argument('--gpu_id', type=int, default=0)
    parser.add_argument('--gt_voxel_folder', type=str, default='voxels_64',
                        help='Folder containing pre-computed GT voxel PLY files')
    parser.add_argument('--color_modes', type=str, nargs='+', default=['ccm', 'height'],
                        choices=['ccm', 'normal', 'height'],
                        help='Color modes for visualization (default: ccm height)')
    parser.add_argument('--only_vis', action='store_true',
                        help='Skip metric computation, only generate visualizations')
    args = parser.parse_args()

    os.environ['CUDA_VISIBLE_DEVICES'] = str(args.gpu_id)

    args.data_dir = "datasets/ERP_3D_FRONT_test"
    args.pred_dirs = [
        "evals/ss_generated/erp_ss_flow_img_dit_L_16l8_bf16",
        "evals/ss_generated/erp_ss_flow_img_dit_L_16l8_bf16_spatial",
        "evals/ss_generated/erp_ss_flow_img_dit_L_16l8_bf16_spatial_da2_inversion_0.3",
        "evals/ss_generated/erp_ss_flow_img_dit_L_16l8_bf16_spatial_da2_inversion_0.5",
        "evals/ss_generated/erp_ss_flow_img_dit_L_16l8_bf16_spatial_da2_inversion_0.7",
    ]

    n_models = len(args.pred_dirs)

    args.model_names = [
        "wo_spatial",
        "spatial",
        "Da2_inv_0.3",
        "Da2_inv_0.5",
        "Da2_inv_0.7",
    ]

    args.num_samples = 0
    args.num_vis = 300
    args.color_modes = ['ccm', 'height']
    args.only_vis = True

    # Model names (full and short)
    full_names = list(args.model_names) + [None] * n_models
    full_names = full_names[:n_models]
    for i in range(n_models):
        if full_names[i] is None:
            full_names[i] = os.path.basename(args.pred_dirs[i].rstrip('/'))
    short_names = [_make_short_name(n) for n in full_names]

    if not args.output_dir:
        args.output_dir = os.path.join('evals', 'results', 'ss_comparison')
    os.makedirs(args.output_dir, exist_ok=True)

    # Find samples from each model
    all_lookups = []  # list of {key: pred_path}
    ref_samples = None
    for mi, pred_dir in enumerate(args.pred_dirs):
        print(f"Finding predictions for model {mi}: {full_names[mi]}...")
        samples = find_pred_samples(pred_dir)
        print(f"  {len(samples)} samples")
        all_lookups.append(build_lookup(samples))
        if ref_samples is None:
            ref_samples = samples  # first model is the reference for iteration

    if not ref_samples:
        print("No samples found in first pred_dir. Check --pred_dirs.")
        return

    # Limit samples if requested
    if args.num_samples > 0:
        ref_samples = ref_samples[:args.num_samples]
        print(f"Limiting to {len(ref_samples)} samples for metrics.")

    # -----------------------------------------------------------------------
    # Compute metrics (skip if --only_vis)
    # -----------------------------------------------------------------------
    vis_samples = []

    if args.only_vis:
        print(f"\n--only_vis: skipping metrics, collecting {args.num_vis} samples for visualization...")
        for sample in ref_samples[:args.num_vis]:
            uuid, room_name, view_idx = sample['uuid'], sample['room_name'], sample['view_idx']
            vis_samples.append({
                'uuid': uuid, 'room_name': room_name, 'view_idx': view_idx,
                'key': f"{uuid}/{room_name}/{view_idx:04d}",
            })
    else:
        all_metrics = []
        gt_cache = {}

        for idx, sample in enumerate(tqdm(ref_samples, desc="Computing metrics")):
            uuid = sample['uuid']
            room_name = sample['room_name']
            view_idx = sample['view_idx']
            key = f"{uuid}/{room_name}/{view_idx:04d}"

            # Load GT (cached per room)
            gt_key = f"{uuid}/{room_name}"
            if gt_key not in gt_cache:
                gt_cache[gt_key] = load_gt_voxel(
                    args.data_dir, uuid, room_name,
                    gt_voxel_folder=args.gt_voxel_folder,
                )
            gt_voxel = gt_cache[gt_key]
            if gt_voxel is None:
                continue

            row = {
                'uuid': uuid,
                'room_name': room_name,
                'view_idx': view_idx,
                'gt_voxels': gt_voxel.sum().item(),
            }

            any_valid = False
            for mi in range(n_models):
                prefix = f'm{mi}'
                pred_path = all_lookups[mi].get(key)
                if pred_path is None:
                    continue
                pred_voxel = load_pred_voxel(pred_path)
                if pred_voxel is None:
                    continue
                any_valid = True
                metrics = compute_voxel_metrics(gt_voxel, pred_voxel)
                cd = compute_chamfer_distance(gt_voxel, pred_voxel)
                row[f'{prefix}_iou'] = metrics['iou']
                row[f'{prefix}_dice'] = metrics['dice']
                row[f'{prefix}_precision'] = metrics['precision']
                row[f'{prefix}_recall'] = metrics['recall']
                row[f'{prefix}_chamfer'] = cd
                row[f'{prefix}_pred_voxels'] = metrics['pred_voxels']

            if not any_valid:
                continue
            all_metrics.append(row)

            if len(vis_samples) < args.num_vis:
                vis_samples.append({
                    'uuid': uuid,
                    'room_name': room_name,
                    'view_idx': view_idx,
                    'key': key,
                })

        del gt_cache
        torch.cuda.empty_cache()

        if len(all_metrics) == 0:
            print("No valid samples found.")
            return

        # -------------------------------------------------------------------
        # Save CSV
        # -------------------------------------------------------------------
        base_fields = ['uuid', 'room_name', 'view_idx', 'gt_voxels']
        metric_names = ['iou', 'dice', 'precision', 'recall', 'chamfer', 'pred_voxels']
        fieldnames = base_fields[:]
        for mi in range(n_models):
            for mn in metric_names:
                fieldnames.append(f'm{mi}_{mn}')

        csv_path = os.path.join(args.output_dir, 'metrics.csv')
        with open(csv_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
            writer.writeheader()
            writer.writerows(all_metrics)
        print(f"\nMetrics CSV saved: {csv_path} ({len(all_metrics)} samples)")

        # -------------------------------------------------------------------
        # Aggregate summary
        # -------------------------------------------------------------------
        def _agg(key):
            vals = [m[key] for m in all_metrics if key in m and m[key] != float('inf')]
            if not vals:
                return float('nan'), float('nan')
            return float(np.mean(vals)), float(np.std(vals))

        summary = {'num_samples': len(all_metrics), 'models': full_names}
        for mi in range(n_models):
            prefix = f'm{mi}'
            summary[full_names[mi]] = {}
            for metric in ['iou', 'dice', 'precision', 'recall', 'chamfer']:
                mean, std = _agg(f'{prefix}_{metric}')
                summary[full_names[mi]][f'{metric}_mean'] = mean
                summary[full_names[mi]][f'{metric}_std'] = std

        summary_path = os.path.join(args.output_dir, 'summary.json')
        with open(summary_path, 'w') as f:
            json.dump(summary, f, indent=2)

        # Print summary table
        col_width = max(25, max(len(s) + 4 for s in short_names))
        header = f"{'Metric':<15}"
        for sn in short_names:
            header += f"{sn:>{col_width}}"
        print("\n" + "=" * len(header))
        print(header)
        print("=" * len(header))
        for metric in ['iou', 'dice', 'precision', 'recall', 'chamfer']:
            line = f"  {metric:<13}"
            for mi in range(n_models):
                mean, std = _agg(f'm{mi}_{metric}')
                line += f" {mean:>10.4f}+/-{std:.4f}  "
            print(line)
        print("=" * len(header))

    # -----------------------------------------------------------------------
    # Visualization
    # -----------------------------------------------------------------------
    if len(vis_samples) == 0:
        print("No samples for visualization.")
        return

    color_modes = args.color_modes
    print(f"\nGenerating visualizations for {len(vis_samples)} samples (color modes: {color_modes})...")
    comp_dir = os.path.join(args.output_dir, 'comparison')
    os.makedirs(comp_dir, exist_ok=True)

    tile = args.tile_size
    itile = args.interior_tile

    # Suffix for output files: '' when only one mode, '_mode' when multiple
    def _suffix(cm):
        return '' if len(color_modes) == 1 else f'_{cm}'

    for batch_start in tqdm(range(0, len(vis_samples), args.batch_vis), desc="Visualizing"):
        batch = vis_samples[batch_start:batch_start + args.batch_vis]
        batch_name = f"batch_{batch_start:03d}_{batch_start + len(batch) - 1:03d}"
        batch_dir = os.path.join(comp_dir, batch_name)

        # Pre-load voxels and camera data for this batch (shared across color modes)
        batch_data = []
        col_labels = []
        for s in batch:
            uuid, room_name, view_idx = s['uuid'], s['room_name'], s['view_idx']
            key = s['key']
            short_label = f"{uuid[:6]}/{room_name[:12]}"
            col_labels.append(short_label)

            gt_voxel = load_gt_voxel(
                args.data_dir, uuid, room_name,
                gt_voxel_folder=args.gt_voxel_folder,
            )
            if gt_voxel is None:
                gt_voxel = torch.zeros(1, 64, 64, 64, dtype=torch.bool)

            cam = load_camera_center(args.data_dir, uuid, room_name, view_idx)

            model_voxels = []
            for mi in range(n_models):
                pred_path = all_lookups[mi].get(key)
                mv = load_pred_voxel(pred_path) if pred_path else None
                if mv is None:
                    mv = torch.zeros(1, 64, 64, 64, dtype=torch.bool)
                model_voxels.append(mv)

            batch_data.append({
                'uuid': uuid, 'room_name': room_name, 'view_idx': view_idx,
                'key': key, 'gt_voxel': gt_voxel, 'cam': cam,
                'model_voxels': model_voxels,
            })

        # Render for each color mode
        for cm in color_modes:
            ext_lists = [[] for _ in range(1 + n_models)]
            td_lists = [[] for _ in range(1 + n_models)]
            tdc_lists = [[] for _ in range(1 + n_models)]

            for bd in batch_data:
                gt_voxel = bd['gt_voxel']
                cam = bd['cam']

                # Render GT
                ext_lists[0].append(render_exterior(gt_voxel, tile=tile, color_mode=cm))
                td_lists[0].append(render_topdown(gt_voxel, tile=tile, color_mode=cm))
                tdc_lists[0].append(
                    render_topdown_cam(gt_voxel, cam, tile=tile, color_mode=cm) if cam is not None
                    else render_topdown(gt_voxel, tile=tile, color_mode=cm)
                )

                # Render each model
                for mi, mv in enumerate(bd['model_voxels']):
                    ext_lists[1 + mi].append(render_exterior(mv, tile=tile, color_mode=cm))
                    td_lists[1 + mi].append(render_topdown(mv, tile=tile, color_mode=cm))
                    tdc_lists[1 + mi].append(
                        render_topdown_cam(mv, cam, tile=tile, color_mode=cm) if cam is not None
                        else render_topdown(mv, tile=tile, color_mode=cm)
                    )

                # Interior (per-sample)
                if cam is not None:
                    cubemap = load_cubemap_images(
                        args.data_dir, bd['uuid'], bd['room_name'], bd['view_idx'], size=itile)
                    if cubemap is not None:
                        gt_int = render_interior(gt_voxel, cam, tile=itile, color_mode=cm)
                        model_ints = [render_interior(mv, cam, tile=itile, color_mode=cm)
                                      for mv in bd['model_voxels']]
                        sample_name = f"{bd['uuid'][:8]}_{bd['room_name']}_{bd['view_idx']:04d}"
                        save_interior_comparison(
                            cubemap, gt_int, model_ints, short_names,
                            os.path.join(comp_dir, sample_name, f'interior{_suffix(cm)}.png'),
                        )

            # Save batch comparisons
            row_labels = ['GT'] + short_names
            save_batch_comparison(ext_lists, row_labels, col_labels,
                                  os.path.join(batch_dir, f'exterior{_suffix(cm)}.png'))
            save_batch_comparison(td_lists, row_labels, col_labels,
                                  os.path.join(batch_dir, f'topdown{_suffix(cm)}.png'))
            save_batch_comparison(tdc_lists, row_labels, col_labels,
                                  os.path.join(batch_dir, f'topdown_cam{_suffix(cm)}.png'))

    print(f"\nDone! Results saved to: {args.output_dir}")
    if not args.only_vis:
        print(f"  Metrics: {os.path.join(args.output_dir, 'metrics.csv')}")
        print(f"  Summary: {os.path.join(args.output_dir, 'summary.json')}")
    print(f"  Visualizations: {comp_dir}/")

    torch.cuda.empty_cache()


if __name__ == '__main__':
    main()
